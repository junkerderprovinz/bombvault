// fortressTextsFor picks the language of a tag such as "de" or "pt-BR": the
// tag itself, then its language, then English.
func fortressTextsFor(lang string) fortressTexts {
	lang = strings.ToLower(lang)
	if tx, ok := fortressCatalog[lang]; ok {
		return tx
	}
	base, _, _ := strings.Cut(lang, "-")
	if tx, ok := fortressCatalog[base]; ok {
		return tx
	}
	return fortressCatalog["en"]
}

func (tx fortressTexts) text(key string) string {
	if v, ok := tx[key]; ok {
		return v
	}
	return fortressCatalog["en"][key]
}

func (tx fortressTexts) format(key string, args ...any) string {
	return fmt.Sprintf(tx.text(key), args...)
}

// section names a section in any of the spellings the code uses for it.
func (tx fortressTexts) section(domain string) string {
	switch domain {
	case "container", "stack":
		domain = "containers"
	case "vm", "VM", "VMs":
		domain = "vms"
	}
	if v := tx.text("section." + domain); v != "" {
		return v
	}
	return domain
}

func (tx fortressTexts) kind(kind string) string {
	if v := tx.text("kind." + kind); v != "" {
		return v
	}
	return kind
}

func (tx fortressTexts) runStatus(runStatus string) string {
	if v := tx.text("status." + runStatus); v != "" {
		return v
	}
	return runStatus
}

// targetLabel names the two entries that are a whole section.
func (tx fortressTexts) targetLabel(targetID string) (string, bool) {
	switch targetID {
	case store.FlashTargetID:
		return tx.section("flash"), true
	case store.ConfigTargetID:
		return tx.section("config"), true
	}
	return "", false
}

// workTitle names what a progress bar is about, such as "Containers: plex".
func (tx fortressTexts) workTitle(key string) string {
	prefix, name, found := strings.Cut(key, ":")
	switch {
	case !found && key == "everything":
		return tx.section("everything")
	case !found:
		return tx.section(key)
	case prefix == "offsite":
		return tx.format("next.offsite", tx.section(name))
	case prefix == "batch":
		return tx.section(name)
	}
	return tx.section(prefix) + ": " + name
}
