export interface I18nContextValue {
  lang: string;
  setLanguage: (code: string) => void;
  /** With a count, picks the form that count needs and puts it in. */
  t: (key: TranslationKey, n?: number) => string;
  languages: Language[];
}

const PLURAL_CATEGORIES = new Set(["zero", "one", "two", "few", "many", "other"]);

/**
 * pluralForms reads the forms a value offers, each labelled with the category
 * it serves: "one={n} backup|other={n} backups". Russian needs three of them,
 * Slovenian four, English two, and most strings none at all, which is what a
 * value without labels is. Every segment has to be labelled, so a sentence that
 * merely contains "=" or "|" stays the one form it is.
 */
function pluralForms(value: string): Map<string, string> | null {
  const forms = new Map<string, string>();
  for (const part of value.split("|")) {
    const at = part.indexOf("=");
    if (at <= 0 || !PLURAL_CATEGORIES.has(part.slice(0, at))) return null;
    forms.set(part.slice(0, at), part.slice(at + 1));
  }
  return forms.size > 0 ? forms : null;
}

/**
 * countText is the form of value that lang uses for n, with n put in. Without
 * a count it answers with the plain form, so a caller that has none renders a
 * sentence rather than the labels.
 */
export function countText(value: string, lang: string, n?: number): string {
  const forms = pluralForms(value);
  let text = value;
  if (forms) {
    const category = n === undefined ? "other" : new Intl.PluralRules(lang).select(n);
    text = forms.get(category) ?? forms.get("other") ?? value;
  }
  return n === undefined ? text : text.split("{n}").join(String(n));
}

// Provide a safe default so `useT()` never throws outside a Provider during tests.
const I18nContext = createContext<I18nContextValue>({
  lang: DEFAULT_CODE,
  setLanguage: () => undefined,
  t: (key, n) => countText(en[key] ?? key, DEFAULT_CODE, n),
  languages: OFFERED_LANGUAGES,
});

/** Mount once at the app root (Layout or main). Children share one language state. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<string>(storedCode);
  // The table actually in use. It starts at whatever is already resident -
  // `en` and `de` are inline - so a German or English reader never waits, and
  // every other language fills in when its chunk lands ([344]).
  const [table, setTable] = useState<Partial<Translations>>(() => locales[storedCode()] ?? en);

  useEffect(() => {
    if (locales[lang]) {
      setTable(locales[lang]);
      return;
    }
    let current = true;
    // `current` rather than an AbortController: two quick switches would
    // otherwise race, and the LAST one has to win regardless of which chunk
    // happens to arrive first.
    void loadLocale(lang).then((t) => {
      if (current) setTable(t);
    });
    return () => {
      current = false;
    };
  }, [lang]);

  // Switch the running tree to a language. Everything setLanguage does EXCEPT
  // writing it down, because this same path also runs when the language is
  // adopted FROM the server, where writing it back would echo it straight
  // home again.
  const adopt = useCallback((code: string) => {
    const offered = OFFERED_LANGUAGES.map((l) => l.code);
    if (!offered.includes(code)) return;
    document.documentElement.setAttribute("lang", code);
    document.documentElement.setAttribute("dir", isRtl(code) ? "rtl" : "ltr");
    // Fetch before the state change where possible, so the switch shows the
    // new language rather than a beat of English on the way to it.
    void loadLocale(code).then(() => setLangState(code));
  }, []);

  const setLanguage = useCallback(
    (code: string) => {
      const offered = OFFERED_LANGUAGES.map((l) => l.code);
      if (!offered.includes(code)) return;
      localStorage.setItem(STORAGE_KEY, code);
      saveDisplayPrefs();
      adopt(code);
    },
    [adopt]
  );

  // `lang` was read once, at mount. When this browser adopts the server's look
  // afterwards the stored code changes with nobody watching, and the tree would
  // stay in the language it booted in — English, on a browser whose data was
  // just cleared, which is half of what #191 looked like.
  useEffect(() => {
    const onAdopted = () => adopt(storedCode());
    window.addEventListener(ADOPTED_EVENT, onAdopted);
    return () => window.removeEventListener(ADOPTED_EVENT, onAdopted);
  }, [adopt]);

  const t = useCallback(
    (key: TranslationKey, n?: number): string => countText(table[key] ?? en[key] ?? key, lang, n),
    [table, lang]
  );

  return createElement(
    I18nContext.Provider,
    { value: { lang, setLanguage, t, languages: OFFERED_LANGUAGES } },
    children
  );
}

/**
 * useT() — reads from the shared I18nContext.
 * Must be called inside <I18nProvider>. Any setLanguage call re-renders the whole tree.
 */
export function useT(): I18nContextValue {
  return useContext(I18nContext);
}

